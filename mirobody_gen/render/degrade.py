"""Image tiers: turn a clean PDF into a scan, phone photo, photocopy/fax, screen photo or screenshot.

Design follows three principles from PureDocBench (arXiv:2605.07492, the benchmark introduced by the
WeVisDoc paper):

1. **Aligned views share one ground truth.** The same source document is rendered into Clean, Digital
   Degraded and Real Degraded views with a single annotation -- degradation changes pixels, not content.
   So every scene here starts from the same PDF, keeps the manifest's printed and semantic truth as is,
   and only adds `tier` / `scene` / `severity` / `ops`.
2. **A scene is a chain of operators, not a single one.** PureDocBench's ten digital-degradation scenes
   (aged_archive, book_binding, multi_gen_copy, fax_thermal, low_quality_print, ink_bleed,
   heavy_compression, uneven_lighting, geometric_distort, noise_blur_combo) are each a fixed operator
   combination drawn from four stages -- paper, print/copy, capture, digital processing -- scaled by one
   0-1 severity (mild 0.3 / moderate 0.6 / severe 0.9). Its real capture chains are four: phone photo of
   paper (flat/creased/bent/under a cover x normal/low light/flash x top-down/oblique), phone photo of a
   photocopy, phone photo of a screen, and a screenshot forwarded through chat compression. Our scenes
   follow those two tables and are named by this repo's tiers: T2 scan, T3 phone photo, T4 degraded
   document, T6 screenshot/screen photo.
3. **A view where content is unreadable keeps no source truth.** PureDocBench's training rule keeps the
   source annotation only while every supervised item stays visible and legible, otherwise it rejects the
   sample or crops the annotation to what remains visible. Here every scene keeps the whole page in frame
   (top-down shot, long screenshot, full-page scan); the severe tier goes into the `stress` bucket, not
   the main leaderboard, and per-line readability is reported by `audit/readability.py` via OCR, scene by
   scene -- a report, not a gate, since OCR missing a line doesn't mean a human would.

Depends only on PIL and numpy (PureDocBench's own implementation uses OpenCV; this repo avoids that
dependency for one layer). Deterministic: every random draw comes from `RandomState(sha1(doc_id + scene))`,
byte-identical for a given seed.

Every output image carries a synthetic mark -- JPEG's EXIF ImageDescription/Software, PNG's text chunk --
a second control, beyond the banner, for the "mistaken as real" risk in docs/zh-CN/plan.md §4.1(d).
"""

