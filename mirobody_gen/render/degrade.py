def _s(**kw):
    """A parameter sampler: a fixed value, or an (lo, hi) range interpolated by severity."""
    def sample(rng, sev):
        out = {}
        for k, v in kw.items():
            if isinstance(v, tuple) and len(v) == 2 and all(isinstance(x, (int, float)) for x in v):
                lo, hi = v
                val = lo + (hi - lo) * sev
                out[k] = int(round(val)) if isinstance(lo, int) and isinstance(hi, int) else round(float(val), 3)
            else:
                out[k] = v
        return out
    return sample


