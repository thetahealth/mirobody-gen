def rasterize(pdf_bytes: bytes, dpi: int) -> list[Image.Image]:
    import fitz

    out = []
    with fitz.open("pdf", pdf_bytes) as doc:
        for page in doc:
            pix = page.get_pixmap(dpi=dpi, colorspace=fitz.csRGB, alpha=False)
            out.append(Image.frombytes("RGB", (pix.width, pix.height), pix.samples))
    return out


def content_margins(pdf_bytes: bytes, dpi: int) -> dict[int, tuple[int, int, int, int]]:
    """Each page's text content box, in pixels: (left, top, right, bottom). The page margin outside it is
    where a finger may press."""
    import fitz

    out = {}
    with fitz.open("pdf", pdf_bytes) as doc:
        for i, page in enumerate(doc):
            words = page.get_text("words")
            k = dpi / 72
            if words:
                x0 = min(w[0] for w in words); y0 = min(w[1] for w in words)
                x1 = max(w[2] for w in words); y1 = max(w[3] for w in words)
                out[i] = (int(x0 * k), int(y0 * k), int(x1 * k), int(y1 * k))
    return out


def annotate(pdf_bytes: bytes, seed_text: str, targets: list[str], max_marks: int = 3) -> tuple[bytes, list[str]]:
    """A doctor's or the patient's own pen circling an abnormal value: draws an ellipse around each target
    string on the PDF, never covering the text. Augraphy calls this class Markup/Scribbles; on real
    reports, what gets circled is usually exactly the abnormal item. Returns (new PDF, the circled strings)."""
    import fitz

    rng = np.random.RandomState(int(hashlib.sha1(f"{seed_text}:annotate".encode()).hexdigest()[:8], 16))
    marked: list[str] = []
    with fitz.open("pdf", pdf_bytes) as doc:
        order = list(rng.permutation(len(targets)))
        for idx in order:
            if len(marked) >= max_marks:
                break
            text = targets[idx]
            for page in doc:
                rects = page.search_for(text)
                if rects:
                    r = rects[0]
                    pad = 2.5
                    color = (0.75, 0.1, 0.1) if rng.rand() < 0.6 else (0.1, 0.2, 0.7)
                    shape = page.new_shape()
                    shape.draw_oval(fitz.Rect(r.x0 - pad - 2, r.y0 - pad, r.x1 + pad + 2, r.y1 + pad))
                    shape.finish(color=color, width=0.9 + rng.rand() * 0.6)
                    shape.commit()
                    marked.append(text)
                    break
        return doc.tobytes(garbage=1, deflate=True, no_new_id=True), marked


def apply_scene(pages: list[Image.Image], scene: str, severity: str, seed_text: str,
                content_margins: dict[int, tuple[int, int, int, int]] | None = None
                ) -> tuple[list[Image.Image], list[dict]]:
    """Run the same operator chain on every page (pages from one shoot get similar but not identical
    parameters: the rng carries over from page to page). Returns (page images, per-operator parameter log)."""
    rng = np.random.RandomState(int(hashlib.sha1(f"{seed_text}:{scene}".encode()).hexdigest()[:8], 16))
    sev = SEVERITY[severity]
    log: list[dict] = []
    out_pages = []
    for index, page in enumerate(pages):
        arr = _to_np(page)
        for op_name, sampler in SCENES[scene]["stages"]:
            params = sampler(rng, sev)
            call = dict(params)
            if op_name in CONTEXT_OPS:
                key = CONTEXT_OPS[op_name]
                if key == "_next":
                    call["_next"] = _to_np(pages[index + 1]) if index + 1 < len(pages) else None
                elif key == "margin":
                    call["margin"] = (content_margins or {}).get(index)
            result = OPS[op_name](arr, rng, **call)
            if isinstance(result, tuple):
                arr, extra = result
                params = {**params, **extra}
            else:
                arr = result
            if len(out_pages) == 0:
                log.append({"op": op_name, **params})
        out_pages.append(_to_img(arr))
    return out_pages, log


def encode(pages: list[Image.Image], container: str, doc_title: str) -> bytes:
    """jpg / png: a single page image; scanpdf: a multi-page, text-layer-free image PDF."""
    if container == "jpg":
        exif = Image.Exif()
        exif[0x010E] = SYNTHETIC_MARK          # ImageDescription
        exif[0x0131] = "mirobody-gen"          # Software
        buf = io.BytesIO()
        pages[0].save(buf, "JPEG", quality=92, exif=exif.tobytes())
        return buf.getvalue()
    if container == "png":
        meta = PngImagePlugin.PngInfo()
        meta.add_text("Description", SYNTHETIC_MARK)
        meta.add_text("Software", "mirobody-gen")
        buf = io.BytesIO()
        pages[0].save(buf, "PNG", pnginfo=meta, optimize=True)
        return buf.getvalue()
    if container == "scanpdf":
        import fitz

        pdf = fitz.open()
        for page in pages:
            buf = io.BytesIO()
            page.save(buf, "JPEG", quality=85)
            w, h = page.size
            rect = fitz.Rect(0, 0, w * 72 / 200, h * 72 / 200)
            p = pdf.new_page(width=rect.width, height=rect.height)
            p.insert_image(rect, stream=buf.getvalue())
        pdf.set_metadata({"title": doc_title, "subject": "SYNTHETIC", "keywords": "synthetic; mirobody-gen; scan",
                          "creator": "mirobody-gen", "producer": "mirobody-gen"})
        return pdf.tobytes(garbage=4, deflate=True, no_new_id=True)
    raise ValueError(container)
